"""T050 — `factory gate run`, override resolution, `factory override`; T059 workflow.

contracts/gates.md § Override resolution: a failing gate looks for
`bus/orders/<order-id>/override-NN.yaml` with `gate: <id>` at the PR head.
- `class: drift` (from the registry, not the message): an override by `orchestrator`
  or `governor` with a reason turns it into "overridden: <reason>"; counted.
- `class: governor-only`: only `actor: governor`; when `identity.mode` is `verified`,
  the `IdentityPort` must also verify the message; otherwise it stays failed.

The order is the one named by the head branch `wo/<order-id>` (`--head wo/<id>`, or the
PR's head under `--pr N`). Exit 1 on any failure left un-overridden, else 0.

Report (JSON `data` on exit 0, `error.details` on exit 1):
`gates: [{id, class, intents, outcome: pass|fail|overridden, messages, override}]`,
`intents: {<intent id>: [{gate, outcome}]}`, `override_counts: {<gate id>: n}`.
`override` is `{id, actor, reason, verified}` when the outcome is `overridden`.
Every registered CI gate runs (hook rows, which carry `hook_twin_of`, are not CI gates).
Under `--pr N`, one commit status `factory/<gate-id>` per gate is posted on the head.
"""

