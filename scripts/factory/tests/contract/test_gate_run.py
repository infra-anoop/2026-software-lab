# --- --pr: order from the PR head, one commit status per gate --------------------------------


def statuses(github: FakeGitHub, sha: str) -> dict[str, Any]:
    return {status.context: status for status in github.list_commit_statuses(sha)}


def test_gate_run_pr_posts_one_status_per_gate(
    repo: RepoBuilder, factory_cli: FactoryCli, fake_github: FakeGitHub, identity: FakeIdentity
) -> None:
    pair = immutable_violation(repo, override(1, IMMUTABLE))
    pr = repo.make_pr(pair.head_branch)
    result = factory_cli(
        "gate",
        "run",
        "--gate",
        IMMUTABLE,
        "--gate",
        OPEN_OD,
        "--pr",
        str(pr.number),
        "--json",
        repo=repo.path,
    )
    assert_exit(result, exit_codes.OK)
    posted = statuses(fake_github, pair.head_sha)
    assert set(posted) == {f"factory/{IMMUTABLE}", f"factory/{OPEN_OD}"}, posted
    overridden = posted[f"factory/{IMMUTABLE}"]
    assert overridden.state == "success", overridden
    assert overridden.description.startswith("overridden: "), overridden
    assert posted[f"factory/{OPEN_OD}"].state == "success"


def test_gate_run_pr_posts_failure_and_resolves_order_from_head(
    repo: RepoBuilder, factory_cli: FactoryCli, fake_github: FakeGitHub, identity: FakeIdentity
) -> None:
    pair = open_od_violation(repo)
    pr = repo.make_pr(pair.head_branch)
    result = factory_cli("gate", "run", "--gate", OPEN_OD, "--pr", str(pr.number), repo=repo.path)
