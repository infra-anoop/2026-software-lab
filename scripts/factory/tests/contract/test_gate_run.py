def override_cli(factory_cli: FactoryCli, repo: RepoBuilder, gate: str, *extra: str) -> CliResult:
    return factory_cli(
        "override",
        ORDER_ID,
        "--gate",
        gate,
        "--reason",
        REASON,
        "--pr",
        "1",
        *extra,
        repo=repo.path,
    )


def read_yaml(path: Path) -> dict[str, Any]:
    assert path.is_file(), f"{path} was not written"
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    assert isinstance(data, dict), data
    return data


def test_override_cli_writes_numbered_messages_with_registry_class(
    repo: RepoBuilder, factory_cli: FactoryCli, identity: FakeIdentity
) -> None:
    pair = immutable_violation(repo)
    repo.checkout(pair.head_branch)
    first = override_cli(factory_cli, repo, IMMUTABLE, "--actor-model", "claude-opus-5.5")
    second = override_cli(factory_cli, repo, IMMUTABLE, "--actor-model", "claude-opus-5.5")
    assert_exit(first, exit_codes.OK)
    assert_exit(second, exit_codes.OK)
    one = read_yaml(repo.path / ORDER_DIR / "override-01.yaml")
    two = read_yaml(repo.path / ORDER_DIR / "override-02.yaml")
    assert (one["id"], two["id"]) == (f"{ORDER_ID}.override-01", f"{ORDER_ID}.override-02")
    assert one["gate"] == IMMUTABLE and one["gate_class"] == "drift", one
    assert one["actor"] == "orchestrator" and one["reason"] == REASON, one
    repo.commit("overrides")
    result = gate_run(
        factory_cli, repo, BaseHeadPair(pair.base_sha, repo.head_sha(), pair.head_branch), IMMUTABLE
    )
    assert_exit(result, exit_codes.OK)
    assert report(result).get("override_counts", {}).get(IMMUTABLE) == 2


